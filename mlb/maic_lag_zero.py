# ======================================================== the overlap-aware se, cells
def _overlap_var(rs, kd):
    """sum_{i,j} N_ij c_ij / (n^2 R^2) over the configurations rs of one cell: the
    variance of the equal-weight mean of the k = 0 shares when configurations share
    seeds (see the module docstring). kd[key] = the int8 array of selected k by draw
    (seed seed0 + r). Returns (variance, number of ordered pairs i != j that share
    seeds, mean shared fraction)."""
    n = len(rs)
    R = rs[0]["R"]
    assert all(x["R"] == R for x in rs)
    ind = [(kd[_key(x)] == 0).astype(np.float64) for x in rs]
    tot = 0.0
    n_pairs = 0
    shared = []
    for i in range(n):
        si = rs[i]["seed0"]
        for j in range(n):
            sj = rs[j]["seed0"]
            lo, hi = max(si, sj), min(si + R, sj + R)
            if hi <= lo:
                continue
            a = ind[i][lo - si:hi - si]
            b = ind[j][lo - sj:hi - sj]
            N = hi - lo
            cij = float(np.mean(a * b) - np.mean(a) * np.mean(b))
            tot += N * cij
            if i != j:
                n_pairs += 1
                shared.append(N / R)
    return tot / (n * n * R * R), n_pairs, (float(np.mean(shared)) if shared else 0.0)


def _cells(rows, expected, kd):
    """Aggregate configurations into (m, T) cells: equal weight per configuration,
    as the calibration's lambda-averaging. se of the cell share: the overlap-aware one
    (_overlap_var); se_indep = sqrt(sum p_i(1-p_i)/R_i)/n assumes independent
    configurations and se_upper = mean_i sqrt(p_i(1-p_i)/R_i) is the
    perfect-correlation bound. Cells come out in the order m, T."""
    out = {}
    for r in rows:
        out.setdefault((r["m"], r["T"]), []).append(r)
    cells = []
    for (m, T), rs in sorted(out.items()):
        n = len(rs)
        p = np.array([x["counts"][0] / x["R"] for x in rs])
        var = np.array([pi * (1 - pi) / x["R"] for pi, x in zip(p, rs)])
        tot = np.sum([x["counts"] for x in rs], axis=0)
        ntot = int(tot.sum())
        kbar = np.array([np.dot(np.arange(KMAX + 1), x["counts"]) / x["R"]
                         for x in rs])
        v_ov, n_pairs, mean_shared = _overlap_var(rs, kd)
        cells.append(dict(
            m=m, T=T, n_configs=n, n_configs_expected=int(expected[(m, T)]),
            cell_complete=bool(n == expected[(m, T)]),
            R_per_config=int(rs[0]["R"]), draws=ntot,
            share_k0=float(p.mean()), se_share_k0=float(np.sqrt(max(v_ov, 0.0))),
            se_share_k0_indep=float(np.sqrt(var.sum()) / n),
            se_share_k0_upper=float(np.mean(np.sqrt(var))),
            overlapping_pairs=int(n_pairs), mean_shared_fraction=mean_shared,
            share_k0_min_config=float(p.min()), share_k0_max_config=float(p.max()),
            share_k_le1=float(np.mean([(x["counts"][0] + x["counts"][1]) / x["R"]
                                       for x in rs])),
            share_k_eq_kmax=float(np.mean([x["counts"][KMAX] / x["R"] for x in rs])),
            mean_k=float(kbar.mean()),
            hist_pooled=[int(v) for v in tot]))
    return cells


# ================================================================== text of the files
def _fmt(v):
    return repr(v) if isinstance(v, float) else str(v)


def cell_line(x):
    """One line of maic_k_by_cell.csv."""
    return (",".join(_fmt(x[k]) for k in CELL_COLS) + ","
            + ",".join(str(v) for v in x["hist_pooled"]))


def config_line(r):
    """One line of maic_k_by_config.csv."""
    p = r["counts"][0] / r["R"]
    se = float(np.sqrt(p * (1 - p) / r["R"]))
    return (f"{draws_key(r)},{r['m']},{r['T']},"
            f"{'_'.join(repr(x) for x in r['lambdas'])},{r['seed0']},{r['R']},"
            + ",".join(str(x) for x in r["counts"])
            + f",{p!r},{se!r},{r['verify_n']},{r['verify_notok']},"
              f"{r['verify_max_rel']!r},{r['verify_min_rel_other_k']!r}")


def tabulate(rows):
    """The table of shares from the rows of maic_k_by_cell.csv (dicts of strings, as
    csv.DictReader reads them): one row per (m, T), m, then T."""
    out = []
    for r in rows:
        se = float(r["se_share_k0"])
        m, T = int(r["m"]), int(r["T"])
        out.append(dict(
            m=m, T=T, part=part_label(T), n_configs=int(r["n_configs"]),
            cell_complete=r["cell_complete"], R_per_config=int(r["R_per_config"]),
            share_k0=float(r["share_k0"]), se=se,
            d1=math.floor(-math.log10(2 * se))))
    keys = [(x["m"], x["T"]) for x in out]
    assert len(set(keys)) == len(out), "duplicate (m, T) cell"
    out.sort(key=lambda x: (x["m"], x["T"]))
    return out


def table_lines(rows):
    """The lines (header first) of maic_k0_share_table.csv for by_cell dict rows."""
    return [",".join(TABLE_COLS)] + [",".join(_fmt(x[k]) for k in TABLE_COLS)
                                     for x in tabulate(rows)]


def read_lines(path):
    """The lines of a text file, any line ending; no trailing empty line."""
    text = Path(path).read_bytes().decode("utf-8").replace("\r\n", "\n")
    return text.split("\n")[:-1] if text.endswith("\n") else text.split("\n")


def write_lines(path, lines):
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


def dict_rows(lines):
    """Lines of a csv text (header first) -> dicts of strings."""
    return list(csv.DictReader(lines))


def _cell_key(line):
    f = line.split(",")
    return (int(f[0]), int(f[1]))


def _cfg_cell_key(line):
    f = line.split(",")
    return (int(f[1]), int(f[2]))


def _cfg_sort_key(line):
    f = line.split(",")
    lam = tuple(float(x) for x in f[3].split("_")) if f[3] else ()
    return (int(f[1]), int(f[2]), lam)


# =================================================================== earlier outputs
def load_prior(out, kernel_sha256):
    """The merged state left by earlier invocations in the output folder, or None.
    It is reused only if the four data files agree with each other and the kernel is
    the same; otherwise it is ignored, and the files are written afresh."""
    names = (BY_CELL, BY_CONFIG, DRAWS, SUMMARY)
    if not all((out / n).is_file() for n in names):
        return None
    try:
        summ = json.loads((out / SUMMARY).read_text(encoding="utf-8"))
        cell_ls = read_lines(out / BY_CELL)
        cfg_ls = read_lines(out / BY_CONFIG)
        with np.load(out / DRAWS) as z:
            draws = {k: z[k] for k in z.files}
        if summ.get("kernel_sha256_lf") != kernel_sha256:
            raise ValueError("earlier outputs were made with another kernel")
        if cell_ls[0] != CELL_HEADER or cfg_ls[0] != CONFIG_HEADER:
            raise ValueError("earlier outputs have another layout")
        cells = {_cell_key(x): x for x in cell_ls[1:]}
        cfgs = {}
        for x in cfg_ls[1:]:
            cfgs.setdefault(_cfg_cell_key(x), []).append(x)
        if set(cells) != set(cfgs):
            raise ValueError("by_cell and by_config hold different cells")
        if {x.split(",")[0] for v in cfgs.values() for x in v} != set(draws):
            raise ValueError("by_config and the draws file hold different keys")
    except (OSError, ValueError, KeyError, IndexError) as e:
        print(f"[maic_lag_zero] earlier outputs not reused: {e}", flush=True)
        return None
    return dict(cells=cells, cfgs=cfgs, draws=draws)


# ======================================================================= the check
def _sha_lf(path):
    return hashlib.sha256(Path(path).read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def check_against_reference(out, keys):
    """Compare the regenerated by_cell and table lines of the cells `keys` with the
    reference lines of the same (m, T), and the headers, for the files of
    REFERENCE_OUTPUTS. Returns (ok, detail dict)."""
    gdir = paths.reference_dir(SECTION) / OBJ
    detail = dict(reference_dir=str(gdir.relative_to(paths.REPO_ROOT)).replace("\\", "/"))
    if not gdir.is_dir():
        detail["error"] = "reference folder missing"
        return False, detail
    ok = True
    for name in REFERENCE_OUTPUTS:
        gl, ol = read_lines(gdir / name), read_lines(out / name)
        gmap = {_cell_key(x): x for x in gl[1:]}
        omap = {_cell_key(x): x for x in ol[1:]}
        res = {"header": gl[0] == ol[0]}
        for k in keys:
            same = k in gmap and k in omap and gmap[k] == omap[k]
            res[f"m={k[0]},T={k[1]}"] = bool(same)
            if not same:
                print(f"[maic_lag_zero] DIFFERENT {name} line for (m, T) = {k}:\n"
                      f"  reference: {gmap.get(k)}\n  regen : {omap.get(k)}", flush=True)
        detail[name] = res
        ok = ok and all(res.values())
    n = len(keys)
    for name in REFERENCE_OUTPUTS:
        n_same = sum(v for k, v in detail[name].items() if k != "header")
        print(f"[maic_lag_zero] check {name}: {n_same}/{n} lines identical to the "
              f"reference (header identical: {detail[name]['header']})", flush=True)
    return bool(ok), detail


# ========================================================================= main
def execute(tasks, jobs):
    """Run the tasks, in the calling process (jobs = 1) or in a pool; the results come
    back in completion order."""
    results = []
    t0 = time.time()
    if jobs == 1:
        for t in tasks:
            results.append(_task(t))
            print(f"  {len(results)}/{len(tasks)} tasks, {time.time() - t0:.0f}s",
                  flush=True)
        return results
    with ProcessPoolExecutor(max_workers=jobs) as ex:
        futs = [ex.submit(_task, t) for t in tasks]
        for f in as_completed(futs):
            results.append(f.result())
            n = len(results)
            if n % 50 == 0 or n == len(tasks):
                print(f"  {n}/{len(tasks)} tasks, {time.time() - t0:.0f}s", flush=True)
    return results


def main(argv=None, out=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--part", choices=(*PARTS, "all"),
                   help="whole parts of the schedule")
    g.add_argument("--cells", nargs="+", metavar="m:T",
                   help="single cells of the schedule")
    ap.add_argument("--check", action="store_true",
                    help="compare the regenerated lines with the reference lines")
    ap.add_argument("--jobs", type=int, default=4, help="worker processes")
    ap.add_argument("--verify", type=int, default=20,
                    help="s2_AR identity self-test on the first V draws of each task")
    a = ap.parse_args(argv)
    if sys.flags.optimize:
        raise SystemExit("refusing to run under -O: the checks are asserts")
    if a.jobs < 1 or a.verify < 0:
        raise SystemExit("--jobs must be >= 1 and --verify >= 0")

    from mlb import kernel_numba as K
    P = dict(K.DEFAULTS)
    assert P["kmax"] == KMAX, P["kmax"]
    if a.cells:
        cells = parse_cells(a.cells, P)
    else:
        names = list(PARTS) if a.part == "all" else [a.part]
        cells = [x for nm in names for x in part_cells(P, nm)]
    tasks, expected = make_tasks(P, cells, a.verify)

    out = Path(out) if out is not None else paths.out_dir(SECTION) / OBJ
    out.mkdir(parents=True, exist_ok=True)
    ksha = _sha_lf(os.path.join(_REPO, "mlb", "kernel_numba.py"))
    jobs = min(a.jobs, len(tasks))
    print(f"[maic_lag_zero] {len(cells)} cells, {len(tasks)} tasks, "
          f"jobs={jobs}, kernel sha256 {ksha}", flush=True)

    t0 = time.time()
    _warm()
    results = execute(tasks, jobs)
    wall = time.time() - t0

    rows, kd = [], {}
    for res in results:
        key = _key(res)
        assert key not in kd, key
        kd[key] = np.frombuffer(res.pop("kdraw"), dtype=np.int8).copy()
        assert kd[key].shape == (res["R"],)
        assert np.array_equal(np.bincount(kd[key], minlength=KMAX + 1), res["counts"])
        assert sum(res["counts"]) == res["R"], res
        rows.append(res)
    rows.sort(key=lambda r: (r["m"], r["T"], r["lambdas"]))
    assert len(rows) == len(tasks)
    new_cells = _cells(rows, expected, kd)
    assert all(x["cell_complete"] for x in new_cells)
    new_keys = [(x["m"], x["T"]) for x in new_cells]
    assert len(set(new_keys)) == len(new_cells)

    # merge with the cells of earlier invocations, then write
    prior = load_prior(out, ksha)
    keep = set(prior["cells"]) - set(new_keys) if prior else set()
    cell_ls = {k: prior["cells"][k] for k in keep}
    cfg_ls = {k: list(prior["cfgs"][k]) for k in keep}
    draws = {}
    for k in keep:
        for x in cfg_ls[k]:
            draws[x.split(",")[0]] = prior["draws"][x.split(",")[0]]
    for x in new_cells:
        cell_ls[(x["m"], x["T"])] = cell_line(x)
    for r in rows:
        cfg_ls.setdefault((r["m"], r["T"]), []).append(config_line(r))
        draws[draws_key(r)] = kd[_key(r)]
    cell_sorted = [cell_ls[k] for k in sorted(cell_ls)]
    cfg_sorted = sorted((x for v in cfg_ls.values() for x in v), key=_cfg_sort_key)
    write_lines(out / BY_CELL, [CELL_HEADER] + cell_sorted)
    write_lines(out / BY_CONFIG, [CONFIG_HEADER] + cfg_sorted)
    np.savez_compressed(out / DRAWS, **{x.split(",")[0]: draws[x.split(",")[0]]
                                        for x in cfg_sorted})
    write_lines(out / TABLE, table_lines(dict_rows([CELL_HEADER] + cell_sorted)))

    vn = sum(r["verify_n"] for r in rows)
    others = [r["verify_min_rel_other_k"] for r in rows if r["verify_n"]]
    verify = dict(draws_checked=vn, not_ok=sum(r["verify_notok"] for r in rows),
                  max_rel_at_recorded_k=max(r["verify_max_rel"] for r in rows),
                  min_rel_at_other_k=min(others) if others else None)
    verify_ok = (vn == 0 or (verify["not_ok"] == 0
                             and verify["max_rel_at_recorded_k"] < VERIFY_TOL
                             and verify["min_rel_at_other_k"] > VERIFY_OTHER_MIN))
    verify["passed"] = bool(verify_ok)

    summary = dict(
        object=OBJ, kernel="mlb/kernel_numba.py", kernel_sha256_lf=ksha, kmax=KMAX,
        seed_base=P["seed_base"],
        seed_rule="config_seed + r",
        se_rule="overlap-aware: sum_ij N_ij c_ij / (n^2 R^2); the configurations of a "
                "cell share seeds",
        cells_computed=[list(x) for x in cells], n_tasks=len(tasks),
        verify=verify, numpy=np.__version__, python=sys.version.split()[0])
    rc = 0
    if not verify_ok:
        print(f"[maic_lag_zero] SELF-TEST FAILED: {verify}", flush=True)
        rc = 3
    if a.check:
        ok, detail = check_against_reference(out, new_keys)
        summary["check"] = dict(passed=ok, detail=detail)
        if not ok:
            print("[maic_lag_zero] CHECK FAILED: the regenerated lines differ from "
                  "the reference", flush=True)
            rc = rc or 4
        else:
            print("[maic_lag_zero] CHECK PASSED", flush=True)
    with open(out / SUMMARY, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(summary, fh, indent=1)
        fh.write("\n")

    print(f"[maic_lag_zero] done in {wall:.0f}s; self-test {verify}", flush=True)
    for x in new_cells:
        print(f"  m={x['m']} T={x['T']:>3} n={x['n_configs']:>2} "
              f"P(k=0)={x['share_k0']:.4f} se={x['se_share_k0']:.4f} "
              f"(indep {x['se_share_k0_indep']:.4f}, "
              f"upper {x['se_share_k0_upper']:.4f}) "
              f"[{x['share_k0_min_config']:.4f},{x['share_k0_max_config']:.4f}] "
              f"mean k={x['mean_k']:.3f}", flush=True)
    return rc


if __name__ == "__main__":
    sys.exit(main())
