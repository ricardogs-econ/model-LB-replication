"""The MAIC-selected lag order under the i.i.d. calibration design: P(k = 0).

What it computes
----------------
For each configuration (T, m, lambdas) of the kernel's grid (kernel_numba.DEFAULTS,
enumerate_configs) it measures, under the unit-root null (c = 0), how often the MAIC
arm of the statistic selects the lag order k = 0:

    for r in 0..R-1:
        eps = default_rng((seed0 + r) % (2**63 - 1)).standard_normal(T)
        y   = gen_dgp_nb(T, 0.0, eps)                       # u_0 = 0, y = u
        k   = maic_select_k_nb(ols_detrend_nb(y, Z), 12)    # the MAIC arm of mstats_nb

seed0 is the kernel's config_seed(P, T, m, lambdas) (P = kernel_numba.DEFAULTS). The
selected k does not depend on c-bar: maic_select_k_nb receives the OLS-detrended
series, which carries no c-bar, so the share is that of the MAIC arm at c-bar = -7.

A cell (m, T) pools its configurations with equal weight, as the calibration
averages over the break fractions lambda. The grid is the article's, T in {45, 50, 60,
80, 100, 150, 200, 300} and m in 0..5 (T >= 45, 45, 45, 45, 60, 80 for m = 0..5): 43
cells.

Standard error of a cell share
------------------------------
The configurations of one cell do NOT draw independent streams. config_seed moves
by 37 * round(1000 * lambda_1) (+ 37**2 * round(1000 * lambda_2) ...), a few
thousand between neighboring lambdas, so at R = 20000 neighboring configurations
share most of their seeds. The same seed gives the same y in every configuration
of a T (gen_dgp_nb: y = u); only the OLS detrending (the break dates) differs.
The reported se is therefore the overlap-aware one,

    Var(mean_i phat_i) = sum_{i,j} N_ij c_ij / (n^2 R^2),

N_ij the number of seeds configurations i and j share, c_ij the covariance of their
k = 0 indicators on those shared draws (c_ii = phat_i (1 - phat_i)).
maic_k_by_cell.csv writes the independence se (a lower bound here) and the
perfect-correlation bound (mean_i sd_i) beside it. The digit rule is
d = floor(-log10(2 se)), the 'd1' column of the table.

Schedule (built in, so that a subset reproduces its rows of the reference output)
---------------------------------------------------------------------------------
    part       T                    m      R per config  cells  configs
    T45_100    45 50 60 80 100      0..5   20000         25     242
    T150_300   150 200 300          0..5   10000         18     162

Cost, one invocation per part, in task CPU time (divide by --jobs; each invocation
also compiles the kernel, about 35 s in a fresh tree): T45_100 about 17
CPU-minutes, T150_300 about 14. Run them as separate invocations. A single cell
takes seconds to a minute: (m = 0, T = 300) about 8 s, (m = 5, T = 80) about 22 s of
task time.

Usage (from the root of the package)
------------------------------------
    python mlb/maic_lag_zero.py --part T150_300 --check --jobs 4
    python mlb/maic_lag_zero.py --part all --check --jobs 8
    python mlb/maic_lag_zero.py --cells 0:300 5:80 --check

  --part {T45_100,T150_300,all}   whole parts of the schedule
  --cells m:T ...                 single cells
  --check     compare every regenerated by_cell line and table line with the line of
              the same (m, T) in reference/calibration/maic_lag_zero/;
              exit status 4 on any difference
  --jobs N    worker processes (1 = in the calling process)
  --verify V  built-in self-test: for the first V draws of each task, s2_AR implied
              by the MSB of mstats_nb(y, Z, -7.0, 1, 12) must equal
              s2ar_at_k_nb(ytilde_GLS, k) at the recorded k (and at no other k);
              default 20, 0 switches it off; exit status 3 if it fails

Outputs, under output/critical_values/maic_lag_zero/
    maic_k_by_cell.csv       one row per cell (31 columns)
    maic_k0_share_table.csv  one row per cell: the share of k = 0, its se and d1
    maic_k_by_config.csv     one row per configuration (histogram of k, seed, R)
    maic_k_draws.npz         the selected k of every draw (an optional regenerated
                             output: lets anyone recompute each share and se)
    maic_k_summary.json      the run record (the kernel's sha256, the cells, the
                             self-test)
The four data files are merged by cell: cells computed by this invocation replace
their rows, rows of cells computed by earlier invocations (the other parts) are
kept, so the two parts together give the same by_cell and table files as one run
over all parts. All files are written with LF line endings.
"""
