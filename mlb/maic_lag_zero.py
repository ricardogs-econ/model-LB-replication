# ================================================================== the schedule
def part_label(T):
    """The name of the part that holds the cells (., T)."""
    for name, spec in PARTS.items():
        if T in spec["T"]:
            return name
    raise KeyError(T)


def part_cells(P, name):
    """The cells (m, T, R) of one part."""
    from mlb import kernel_numba as K
    spec = PARTS[name]
    cells = []
    for m in spec["m"]:
        for T in spec["T"]:
            if K.enumerate_configs(dict(P, T_grid=[T], m_grid=[m])):
                cells.append((m, T, spec["R"]))
    return cells


def schedule(P):
    """Every cell of the schedule, as (m, T, R)."""
    out = []
    for name in PARTS:
        out += part_cells(P, name)
    keys = [x[:2] for x in out]
    assert len(set(keys)) == len(keys)
    return out


def parse_cells(tokens, P):
    """'m:T' tokens -> schedule cells; a cell off the schedule is refused."""
    known = {x[:2]: x for x in schedule(P)}
    out = []
    for tok in tokens:
        try:
            m, T = (int(v) for v in tok.split(":"))
        except ValueError:
            raise SystemExit(f"--cells: cannot read {tok!r}; expected m:T")
        if (m, T) not in known:
            raise SystemExit(f"--cells: (m={m}, T={T}) is not a cell of the "
                             "schedule (m 0..5, T 45..300 on the grid)")
        if known[(m, T)] not in out:
            out.append(known[(m, T)])
    return out


def make_tasks(P, cells, V):
    """The tasks (T, m, lambdas, seed0, R, V) of the cells, largest first, and the
    number of configurations each cell holds."""
    from mlb import kernel_numba as K
    tasks, expected = [], {}
    for (m, T, R) in cells:
        cfgs = K.enumerate_configs(dict(P, T_grid=[T], m_grid=[m]))
        assert cfgs, (m, T)
        for (T_, m_, lam) in cfgs:
            seed0 = K.config_seed(P, T_, m_, lam)
            tasks.append((T_, m_, tuple(lam), int(seed0), int(R), int(V)))
        expected[(m, T)] = len(cfgs)
    keys = [(t[0], t[1], t[2]) for t in tasks]
    assert len(set(keys)) == len(keys), "duplicate (T, m, lambdas) task"
    tasks.sort(key=lambda t: (-t[4] * t[0], t[1], t[0], t[2]))
    return tasks, expected


# ======================================================================= one task
def _task(args):
    """One configuration: the histogram of the MAIC-selected k over R draws."""
    T, m, lambdas, seed0, R, V = args
    from mlb import kernel_numba as K
    bp = K.break_pos_from_lambdas(T, lambdas)
    Z = K.build_z_nb(T, bp)
    counts = np.zeros(KMAX + 1, dtype=np.int64)
    kdraw = np.empty(R, dtype=np.int8)         # the selected k of draw r (seed0 + r)
    v_n = 0
    v_max_rel = 0.0         # |s2 implied by mstats_nb / s2ar_at_k_nb(k) - 1| at k
    v_min_other = np.inf    # the same at the nearest OTHER k (discrimination)
    v_notok = 0
    for r in range(R):
        rng = np.random.default_rng((seed0 + r) % (2 ** 63 - 1))
        eps = rng.standard_normal(T)
        y = K.gen_dgp_nb(T, 0.0, eps)
        k = K.maic_select_k_nb(K.ols_detrend_nb(y, Z), KMAX)
        counts[k] += 1
        kdraw[r] = k
        if r < V:
            mza, msb, mzt, pt, mpt, ok = K.mstats_nb(y, Z, -7.0, 1, KMAX)
            if ok < 0.5:
                v_notok += 1
                continue
            yt, _ = K.glsd_nb(y, Z, -7.0)
            sumyt2 = float(np.sum(yt[:-1] * yt[:-1])) / (T * T)
            s2_implied = sumyt2 / (msb * msb)
            rel = abs(s2_implied / K.s2ar_at_k_nb(yt, k) - 1.0)
            other = min(abs(s2_implied / K.s2ar_at_k_nb(yt, j) - 1.0)
                        for j in range(KMAX + 1) if j != k)
            v_n += 1
            v_max_rel = max(v_max_rel, rel)
            v_min_other = min(v_min_other, other)
    return dict(T=T, m=m, lambdas=tuple(float(x) for x in lambdas), seed0=int(seed0),
                R=int(R), counts=[int(x) for x in counts],
                verify_n=v_n, verify_notok=v_notok,
                verify_max_rel=float(v_max_rel),
                verify_min_rel_other_k=float(v_min_other) if v_n else float("nan"),
                kdraw=kdraw.tobytes())


def _warm():
    """Compile and cache the kernel functions the tasks use, before the workers."""
    from mlb import kernel_numba as K
    bp = np.array([10, 20], dtype=np.int64)
    Z = K.build_z_nb(30, bp)
    y = K.gen_dgp_nb(30, 0.0, np.random.default_rng(0).standard_normal(30))
    K.maic_select_k_nb(K.ols_detrend_nb(y, Z), KMAX)
    K.mstats_nb(y, Z, -7.0, 1, KMAX)
    yt, _ = K.glsd_nb(y, Z, -7.0)
    K.s2ar_at_k_nb(yt, 0)
    return 0


